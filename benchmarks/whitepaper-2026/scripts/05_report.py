#!/usr/bin/env python3
import json
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
WHITEPAPER_DIR = SCRIPT_DIR.parent
REPO_ROOT = WHITEPAPER_DIR.parent.parent
WP_RESULTS = REPO_ROOT / "perf" / "whitepaper-results.json"
DEFAULT_REPORT = WHITEPAPER_DIR / "results" / "REPORT.md"

COMPARED_TOOLS = ("syslog_generator", "loggen", "flog", "tcpkali")
WORKLOAD_ORDER = ("udp_100rps_256b", "tcp_10krps_1kb", "tls_5krps_1kb", "kafka_50krps_256b")


def fmt_cell(r):
    status = r.get("status", "unknown")
    if status == "completed":
        return "completed"
    if status == "skipped":
        sr = r.get("skip_reason", "")
        if len(sr) > 30:
            sr = sr[:27] + "..."
        return f"skipped ({sr})"
    if status == "dry_run":
        return "dry_run"
    if status == "failed":
        err = r.get("error", "")
        if not err and r.get("measurements", {}).get("fail_reasons"):
            err = "; ".join(r["measurements"]["fail_reasons"])
        if len(err) > 40:
            err = err[:37] + "..."
        return f"failed ({err})"
    if status == "n_a":
        nr = r.get("na_reason", "")
        if len(nr) > 30:
            nr = nr[:27] + "..."
        return f"n/a ({nr})"
    return status


def fallback_metric(r):
    meas = r.get("measurements")
    if not meas:
        return "-"
    if "achieved_msg_per_sec" in meas:
        return f"{meas['achieved_msg_per_sec']:.1f} msg/s"
    if "messages" in meas:
        return f"{meas['messages']} msg"
    if "bytes_received" in meas:
        return f"{meas['bytes_received']} B"
    return "-"


def render_report(data):
    out = []
    out.append("# Whitepaper 2026 — Benchmark Report")
    out.append("")
    out.append(f"> **Auto-generated by** `benchmarks/whitepaper-2026/scripts/05_report.py`")
    out.append(f"> **Generated at:** {data.get('generated_at', 'unknown')}")
    out.append(f"> **Schema version:** {data.get('schema_version', 'unknown')}")
    out.append(f"> **Issue:** #{data.get('issue', '?')}")
    out.append("")

    out.append("## Status")
    out.append("")
    out.append(f"- **Top-level status:** `{data.get('status')}`")
    meaning = data.get("status_meaning", {}).get(data.get("status", ""), "(no description)")
    out.append(f"  - {meaning}")
    host = data.get("host", {})
    out.append(f"- **Host:** {host.get('os', '?')} {host.get('arch', '?')} "
               f"(kernel {host.get('kernel', '?')}, "
               f"{host.get('cpu_count', '?')} cores, "
               f"{host.get('cpu_model', '?')})")
    if host.get("memory_bytes"):
        out.append(f"  - Memory: {host['memory_bytes'] / (1024**3):.1f} GiB")
    out.append("")

    out.append("## Tool Availability")
    out.append("")
    out.append("| Tool | Available | Path | Version |")
    out.append("|---|---|---|---|")
    for name, info in data.get("tool_versions", {}).items():
        avail = "yes" if info.get("available") else "no"
        path = info.get("path") or "-"
        ver = info.get("version") or "-"
        out.append(f"| {name} | {avail} | {path} | {ver} |")
    out.append("")

    out.append("## Workloads (Issue #106 spec)")
    out.append("")
    out.append("| ID | Transport | Target rate | Target size | Duration | Receiver |")
    out.append("|---|---|---|---|---|---|")
    for w in data.get("workloads", []):
        out.append(
            f"| `{w['id']}` | {w['transport']} | "
            f"{w['target_msg_per_sec']} msg/s | "
            f"{w['target_bytes_per_msg']} B | "
            f"{w['duration_secs']}s | "
            f"{w['receiver']['address']}:{w['receiver']['port']} |"
        )
    out.append("")

    runs = data.get("runs", [])
    by_workload = {}
    for r in runs:
        by_workload.setdefault(r["workload_id"], []).append(r)

    if not runs:
        out.append("## Runs Matrix")
        out.append("")
        out.append("**No runs collected yet.** Harness hasn't been executed.")
        out.append("")
        out.append("To populate:")
        out.append("")
        out.append("```bash")
        out.append("make -C benchmarks/whitepaper-2026 all                    # dry-run")
        out.append("make -C benchmarks/whitepaper-2026 all REQUIRE_TOOLS=1    # real")
        out.append("```")
        out.append("")
    else:
        out.append("## Runs Matrix (4 compared tools)")
        out.append("")
        out.append("| Workload | " + " | ".join(COMPARED_TOOLS) + " |")
        out.append("|" + "|".join(["---"] * (len(COMPARED_TOOLS) + 1)) + "|")
        for w in WORKLOAD_ORDER:
            if w not in by_workload:
                continue
            row = [f"`{w}`"]
            for t in COMPARED_TOOLS:
                cell = next((r for r in by_workload[w] if r["tool"] == t), None)
                if cell is None:
                    row.append("-")
                else:
                    row.append(fmt_cell(cell))
            out.append("| " + " | ".join(row) + " |")
        out.append("")

        any_completed = any(r.get("status") == "completed" for r in runs)
        if any_completed:
            out.append("## Throughput (msg/s) — measured cells only")
            out.append("")
            out.append("> **No fabricated measurements.** Only cells with status=`completed`")
            out.append("> are shown below.")
            out.append("")
            out.append("| Workload | " + " | ".join(COMPARED_TOOLS) + " |")
            out.append("|" + "|".join(["---"] * (len(COMPARED_TOOLS) + 1)) + "|")
            for w in WORKLOAD_ORDER:
                if w not in by_workload:
                    continue
                row = [f"`{w}`"]
                for t in COMPARED_TOOLS:
                    cell = next((r for r in by_workload[w] if r["tool"] == t), None)
                    if cell is None or cell.get("status") != "completed":
                        row.append("-")
                    else:
                        row.append(fallback_metric(cell))
                out.append("| " + " | ".join(row) + " |")
            out.append("")

    out.append("## Constraints")
    out.append("")
    c = data.get("constraints", {})
    out.append(f"- No fabricated measurements: **{c.get('no_fabricated_measurements')}**")
    out.append(f"- Min runs per cell: {c.get('min_runs_per_cell')}")
    out.append(f"- Issue: {c.get('issue_106_spec')}")
    out.append("")

    out.append("## How to reproduce")
    out.append("")
    out.append("```bash")
    out.append("make -C benchmarks/whitepaper-2026 all                    # dry-run")
    out.append("make -C benchmarks/whitepaper-2026 all REQUIRE_TOOLS=1    # real")
    out.append("```")
    out.append("")
    out.append("See `benchmarks/whitepaper-2026/METHODOLOGY.md` for the full fairness protocol.")
    out.append("")
    return "\n".join(out)


def main(argv):
    if not WP_RESULTS.exists():
        print(f"ERROR: {WP_RESULTS} not found", file=sys.stderr)
        return 2
    try:
        data = json.loads(WP_RESULTS.read_text())
    except json.JSONDecodeError as e:
        print(f"ERROR: invalid JSON in {WP_RESULTS}: {e}", file=sys.stderr)
        return 3

    md = render_report(data)
    out_path = Path(argv[0]) if argv else DEFAULT_REPORT
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(md)
    print(f"Wrote {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
